-- Q5. Function to return balance for a given account number

-- Create ACCOUNT table

CREATE TABLE ACCOUNT
(
    ACNO      NUMBER(5),
    CNAME     VARCHAR2(30),
    BNAME     VARCHAR2(30),
    BALANCE   NUMBER(12,2),
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (ACNO)
);

INSERT INTO ACCOUNT VALUES (1001, 'ADITYA', 'SBI', 25000);
